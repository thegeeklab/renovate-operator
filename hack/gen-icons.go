var (
	svgTagRe    = regexp.MustCompile(`<svg[^>]*>`)
	attrRe      = regexp.MustCompile(`(\S+)=["']([^"']*)["']`)
	selfCloseRe = regexp.MustCompile(`<(\w+)([^>]*?)/>`)

	errNoSVGTag = errors.New("no <svg> tag found")
)

func main() {
	if len(os.Args) < 2 { //nolint:mnd
		fmt.Fprintf(os.Stderr, "usage: %s <output-file>\n", os.Args[0])
		os.Exit(1)
	}

	outputPath := os.Args[1]

	nodeModules := filepath.Join("node_modules", "lucide-static")
	if _, err := os.Stat(nodeModules); os.IsNotExist(err) {
		fmt.Fprintf(os.Stderr, "error: node_modules/lucide-static not found. Run 'npm install' first.\n")
		os.Exit(1)
	}

	var b strings.Builder
	b.WriteString("// Code generated by hack/gen-icons.go; DO NOT EDIT.\n\n")
	b.WriteString("package view\n\n")

	for i, icon := range icons {
		svgPath := filepath.Join(nodeModules, "icons", icon.fileName+".svg")

		raw, err := os.ReadFile(svgPath)
		if err != nil {
			fmt.Fprintf(os.Stderr, "error reading %s: %v\n", svgPath, err)
			os.Exit(1)
		}

		templName := "Icon" + kebabToPascal(icon.fileName)

		templ, err := svgToTempl(string(raw), templName)
		if err != nil {
			fmt.Fprintf(os.Stderr, "error converting %s: %v\n", icon.fileName, err)
			os.Exit(1)
		}

		b.WriteString(templ)

		if i < len(icons)-1 {
			b.WriteString("\n\n")
		} else {
			b.WriteString("\n")
		}
	}

	existing, _ := os.ReadFile(outputPath) //nolint:gosec
	if string(existing) == b.String() {
		fmt.Printf("no changes to %s\n", outputPath)

		return
	}

	if err := os.WriteFile(outputPath, []byte(b.String()), 0o600); err != nil { //nolint:gosec
		fmt.Fprintf(os.Stderr, "error writing %s: %v\n", outputPath, err)
		os.Exit(1)
	}

	fmt.Printf("generated %s with %d icons\n", outputPath, len(icons))
}

func kebabToPascal(s string) string {
	parts := strings.Split(s, "-")
	for i, part := range parts {
		if len(part) > 0 {
			parts[i] = strings.ToUpper(part[:1]) + part[1:]
		}
	}

	return strings.Join(parts, "")
}

func svgToTempl(raw, funcName string) (string, error) {
	loc := svgTagRe.FindStringIndex(raw)
	if loc == nil {
		return "", errNoSVGTag
	}
	svgMatch := raw[loc[0]:loc[1]]

	inner := strings.TrimSpace(strings.TrimSuffix(strings.TrimSpace(raw[loc[1]:]), "</svg>"))

	attrs := attrRe.FindAllStringSubmatch(svgMatch, -1)

	var kept []struct{ name, value string }

	skip := map[string]bool{"width": true, "height": true, "class": true}

	for _, m := range attrs {
		if !skip[m[1]] {
			kept = append(kept, struct{ name, value string }{m[1], m[2]})
		}
	}

	inner = selfCloseRe.ReplaceAllStringFunc(inner, func(match string) string {
		parts := selfCloseRe.FindStringSubmatch(match)

		return "<" + parts[1] + strings.TrimRight(parts[2], " ") + "></" + parts[1] + ">"
	})

	innerLines := strings.Split(inner, "\n")

	var indented []string

	for _, line := range innerLines {
		trimmed := strings.TrimSpace(line)
		if trimmed != "" {
			indented = append(indented, "\t\t"+trimmed)
		}
	}

	var b strings.Builder
	fmt.Fprintf(&b, "templ %s(class string) {\n", funcName)
	b.WriteString("\t<svg\n")

	for _, a := range kept {
		fmt.Fprintf(&b, "\t\t%s=\"%s\"\n", a.name, a.value)
	}

	b.WriteString("\t\tclass={ class }\n")
	b.WriteString("\t>\n")

	for _, line := range indented {
		fmt.Fprintf(&b, "%s\n", line)
	}

	b.WriteString("\t</svg>\n}")

	return b.String(), nil
}
